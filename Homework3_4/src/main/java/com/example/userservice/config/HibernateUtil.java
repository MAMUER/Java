package com.example.userservice.config;

import org.hibernate.SessionFactory;
import org.hibernate.cfg.Configuration;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.Statement;

public final class HibernateUtil {

    private static final Logger LOGGER = LoggerFactory.getLogger(HibernateUtil.class);

    private static final class Holder {
        private static final SessionFactory INSTANCE = buildSessionFactory();

        private static SessionFactory buildSessionFactory() {
            try {
                Configuration configuration = new Configuration().configure();

                String dbUrl = System.getenv("DB_URL");
                String dbUser = System.getenv("DB_USER");
                String dbPassword = System.getenv("DB_PASSWORD");

                if (dbUrl != null && !dbUrl.isBlank()) {
                    configuration.setProperty("hibernate.connection.url", dbUrl);
                }
                if (dbUser != null && !dbUser.isBlank()) {
                    configuration.setProperty("hibernate.connection.username", dbUser);
                }
                if (dbPassword == null || dbPassword.isBlank()) {
                    dbPassword = "postgres"; // NOSONAR
                    LOGGER.warn("DB_PASSWORD is not set, using default value");
                }
                configuration.setProperty("hibernate.connection.password", dbPassword);

                ensureSchema(configuration);

                SessionFactory factory = configuration.buildSessionFactory();
                LOGGER.info("Hibernate SessionFactory created successfully");
                return factory;
            } catch (Exception e) {
                LOGGER.error("Failed to create SessionFactory", e);
                throw new ExceptionInInitializerError(e);
            }
        }

        private static void ensureSchema(Configuration configuration) {
            String url = configuration.getProperty("hibernate.connection.url");
            String user = configuration.getProperty("hibernate.connection.username");
            String password = configuration.getProperty("hibernate.connection.password");
            if (url != null) {
                url = url.trim();
            }
            if (user != null) {
                user = user.trim();
            }
            String createTableSql = "CREATE TABLE IF NOT EXISTS users ("
                    + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "name VARCHAR(100) NOT NULL, "
                    + "email VARCHAR(255) NOT NULL UNIQUE, "
                    + "age INTEGER NOT NULL, "
                    + "created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP"
                    + ")";
            try (Connection connection = DriverManager.getConnection(url, user, password);
                 Statement statement = connection.createStatement()) {
                statement.execute(createTableSql);
                LOGGER.info("Database schema ensured");
            } catch (Exception e) {
                LOGGER.error("Failed to ensure database schema", e);
                throw new ExceptionInInitializerError(e);
            }
        }
    }

    private HibernateUtil() {
    }

    public static SessionFactory getSessionFactory() {
        return Holder.INSTANCE;
    }

    public static void shutdown() {
        if (Holder.INSTANCE != null && !Holder.INSTANCE.isClosed()) {
            Holder.INSTANCE.close();
            LOGGER.info("Hibernate SessionFactory closed");
        }
    }
}