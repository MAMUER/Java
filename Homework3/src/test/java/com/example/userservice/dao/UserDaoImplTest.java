package com.example.userservice.dao;

import com.example.userservice.dto.UserDto;
import org.hibernate.Session;
import org.hibernate.SessionFactory;
import org.hibernate.Transaction;
import org.hibernate.cfg.Configuration;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

import java.util.List;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

class UserDaoImplTest {

    private static SessionFactory sessionFactory;
    private static UserDao userDao;

    @BeforeAll
    static void setUp() {
        sessionFactory = new Configuration()
                .configure("hibernate-test.cfg.xml")
                .buildSessionFactory();
        createSchema();
        userDao = new UserDaoImpl(sessionFactory);
    }

    private static void createSchema() {
        try (Session session = sessionFactory.openSession()) {
            Transaction tx = session.beginTransaction();
            session.createNativeMutationQuery(
                    "CREATE TABLE IF NOT EXISTS users (" +
                            "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                            "name VARCHAR(100) NOT NULL, " +
                            "email VARCHAR(255) NOT NULL UNIQUE, " +
                            "age INTEGER NOT NULL, " +
                            "created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP" +
                            ")"
            ).executeUpdate();
            tx.commit();
        }
    }

    @AfterAll
    static void tearDown() {
        if (sessionFactory != null && !sessionFactory.isClosed()) {
            sessionFactory.close();
        }
    }

    @Test
    void createAndFindById() {
        UserDto dto = new UserDto(null, "Alice", "alice@example.com", 30, null);
        UserDto created = userDao.create(dto);
        assertNotNull(created.id());

        Optional<UserDto> found = userDao.findById(created.id());
        assertTrue(found.isPresent());
        assertEquals("Alice", found.get().name());
    }

    @Test
    void findAll() {
        userDao.create(new UserDto(null, "Bob", "bob@example.com", 25, null));
        List<UserDto> all = userDao.findAll();
        assertFalse(all.isEmpty());
    }

    @Test
    void update() {
        UserDto dto = new UserDto(null, "Charlie", "charlie@example.com", 40, null);
        UserDto created = userDao.create(dto);
        UserDto updateDto = new UserDto(null, "Charles", "charles@example.com", 41, null);
        Optional<UserDto> updated = userDao.update(created.id(), updateDto);
        assertTrue(updated.isPresent());
        assertEquals("Charles", updated.get().name());
    }

    @Test
    void delete() {
        UserDto created = userDao.create(new UserDto(null, "Dave", "dave@example.com", 20, null));
        assertTrue(userDao.delete(created.id()));
        assertFalse(userDao.delete(created.id()));
    }

    @Test
    void findByIdMissing() {
        Optional<UserDto> found = userDao.findById(999999L);
        assertTrue(found.isEmpty());
    }
}
